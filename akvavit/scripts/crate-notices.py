"""Writes the licence notices of every crate compiled into a Rust static library.

Adapted from Madeira's build/rppairing-ios/notices.py, with the crate and the title
as arguments. Walks the normal (non-build, non-dev) dependency graph for
aarch64-apple-ios from Cargo.lock, skips proc-macro crates (they run at compile
time and are not in the binary), and copies each crate's LICENSE/COPYING/NOTICE
files from the cargo registry.

Usage: crate-notices.py <crate directory> <what the library is> <output file>
"""
import json
import subprocess
import sys
from pathlib import Path

crate, title, output = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
metadata = json.loads(subprocess.run(
    ['cargo', 'metadata', '--format-version', '1', '--locked', '--filter-platform', 'aarch64-apple-ios'],
    cwd=crate, check=True, capture_output=True, text=True).stdout)
packages = {p['id']: p for p in metadata['packages']}
nodes = {n['id']: n for n in metadata['resolve']['nodes']}
# In a workspace, resolve.root is unset: start from the package in `crate`.
root = metadata['resolve']['root'] or next(
    p['id'] for p in metadata['packages'] if Path(p['manifest_path']).parent == crate.resolve())

shipped, todo = set(), [root]
while todo:
    node = nodes[todo.pop()]
    for dep in node['deps']:
        if not any(kind['kind'] is None for kind in dep['dep_kinds']):
            continue
        package = packages[dep['pkg']]
        if any('proc-macro' in target['kind'] for target in package['targets']):
            continue
        if dep['pkg'] not in shipped:
            shipped.add(dep['pkg'])
            todo.append(dep['pkg'])

out = [f'Third-party notices for {title}, generated by Akvavit\'s',
       'akvavit/scripts/crate-notices.py from Cargo.lock. Each crate is listed with the',
       'licence it declares and the licence files it ships.', '']
missing, seen = [], {}
for package in sorted((packages[i] for i in shipped), key=lambda p: (p['name'], p['version'])):
    folder = Path(package['manifest_path']).parent
    files = sorted(f for f in folder.iterdir()
                   if f.is_file() and f.name.upper().startswith(('LICENSE', 'LICENCE', 'COPYING', 'NOTICE')))
    out.append('=' * 78)
    out.append(f"{package['name']} {package['version']} ({package.get('license') or 'see files'})")
    if package.get('repository'):
        out.append(package['repository'])
    if not files:
        missing.append(package['name'])
        out.append('(no licence file in the published crate; licence as declared above)')
    for f in files:
        text = f.read_text(errors='replace').rstrip()
        if text in seen:
            out.append(f'--- {f.name}: same text as {seen[text]} above ---')
        else:
            seen[text] = f"{package['name']} {f.name}"
            out += ['', f'--- {f.name} ---', text]
    out.append('')

output.write_text('\n'.join(out) + '\n')
print(f'{len(shipped)} crates -> {output}' + (f" (no licence file: {', '.join(missing)})" if missing else ''))
